/** `text` as `font` can draw it, at most `max` characters. */
export function fontText(font: Font, text: string, max: number): string {
  const plain = text.normalize('NFD').replace(/[̀-ͯ]/g, '').toUpperCase();
  return [...plain].map((ch) => (font.glyphs[ch] ? ch : '?')).slice(0, max).join('');
}

/** Width of `text` (already passed through fontText) in `font`, in pixels. */
export function textWidth(font: Font, text: string): number {
  return text.length ? text.length * (font.w + font.gap) - font.gap : 0;
}

/** Calls `dot` for every lit pixel of `text` (already passed through fontText) in `font`, from (x, y). */
export function eachTextPixel(font: Font, text: string, x: number, y: number, dot: (x: number, y: number) => void): void {
  [...text].forEach((ch, i) => {
    const gx = x + i * (font.w + font.gap);
    font.glyphs[ch].forEach((row, ry) => {
      for (let rx = 0; rx < row.length; rx++) if (row[rx] === '#') dot(gx + rx, y + ry);
    });
  });
}
